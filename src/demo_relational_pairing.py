# Part E -- Gamma_q(x) from Z alone                                     #
# --------------------------------------------------------------------- #
def part_E(rng, M=64, B=400, tau_p=0.02):
    banner("Part E -- Gamma_q(x) recovered from Z alone (no partner indices)")

    x_cells = (np.arange(M) + 0.5) * (L / M)
    mu1 = V_P * tau_p / HBAR                            # pumped contrast C
    net = np.zeros(M)

    for m, xc in enumerate(x_cells):
        rate = 0.0
        for s in (+1, -1):
            chi = rng.uniform(0.0, 2.0 * np.pi)         # site carrier, (S)
            mu_s = s * (K_MODE * xc + PHI_Q) + np.pi / 2.0
            Zh = np.exp(1j * (chi + mu_s)) * B
            Zl = np.exp(1j * chi) * B
            bias = np.real(Zh * np.conj(Zl)) / B ** 2
            rate += 0.5 * mu1 * s * bias                # s = hop direction
        net[m] = rate / tau_p                            # per unit time

    gamma_exact = -(V_P / HBAR) * np.sin(K_MODE * x_cells + PHI_Q)
    rel = np.max(np.abs(net - gamma_exact)) / np.max(np.abs(gamma_exact))

    print(f"  M = {M} cells, B = {B} per row per family, tau_p = {tau_p}")
    print(f"  contrast mu1 = V_p tau_p / hbar = {mu1:.4f}, phi_q = {PHI_Q}")
    print(f"  max|recovered - Gamma_q| / max|Gamma_q| = {rel:.3e}")
    print(f"  at x = L/4 : recovered = {net[M // 4]:+.9f}, "
          f"exact = {gamma_exact[M // 4]:+.9f}")
    print("  -> corrected-sign Gamma_q(x) = -(V_q/hbar) sin(K_q x + phi_q),")
    print("     with the arbitrary site carrier cancelling identically.")
    return x_cells, net, gamma_exact, rel


