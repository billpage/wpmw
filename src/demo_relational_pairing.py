def wrap(a):
    """Wrap to (-pi, pi]."""
    return (a + np.pi) % (2.0 * np.pi) - np.pi


def transported_phase(x_ref, p, theta, x, t):
    """Phi(x,t) = theta + [p (x - x_ref) - E t] / hbar,  E = p^2 / 2m."""
    return theta + (p * (x - x_ref) - p ** 2 / (2.0 * MASS) * t) / HBAR


