def part_A(rng):
    banner("Part A -- mu is a coboundary of Phi; no partnership is stored")

    N = 40
    p = rng.integers(-6, 7, size=N) * 2 * DP           # even sites, §1
    x_ref = rng.uniform(0.0, L, size=N)
    theta = rng.uniform(0.0, 2.0 * np.pi, size=N)

    xs, ts = 2.3, 1.7
    Phi = transported_phase(x_ref, p, theta, xs, ts)
    mu = wrap(Phi[:, None] - Phi[None, :])

    anti = np.max(np.abs(wrap(mu + mu.T)))
    tri = np.max(np.abs(wrap(mu[:, :, None] + mu[None, :, :] - mu[:, None, :])))

    alpha = 0.9137
    Phi_g = transported_phase(x_ref, p, theta + alpha, xs, ts)
    gauge = np.max(np.abs(wrap(mu - wrap(Phi_g[:, None] - Phi_g[None, :]))))

    # Re-referencing: advance each leg to epoch t1 along its own worldline,
    # winding theta at the Lagrangian rate and shifting the time origin.
    t1 = 0.63
    x2 = x_ref + p / MASS * t1
    th2 = theta + (p ** 2 / (2.0 * MASS)) * t1 / HBAR
    Phi_r = transported_phase(x2, p, th2, xs, ts - t1)
    reref = np.max(np.abs(wrap(mu - wrap(Phi_r[:, None] - Phi_r[None, :]))))

    print(f"  ensemble size                              N = {N}")
    print(f"  antisymmetry    max|mu_ij + mu_ji|           = {anti:.3e}")
    print(f"  cocycle         max|mu_ij + mu_jk - mu_ik|   = {tri:.3e}")
    print(f"  global gauge    max|delta mu|                = {gauge:.3e}")
    print(f"  re-referencing  max|delta mu|                = {reref:.3e}")

    # Proposition 3 for arbitrary index pairs, by central differences.
    eps = 1e-5
    dpm = (p[:, None] - p[None, :]) / HBAR
    vbar = (p[:, None] + p[None, :]) / (2.0 * MASS)

    def mu_at(x, t):
        f = transported_phase(x_ref, p, theta, x, t)
        return f[:, None] - f[None, :]

    dx_num = (mu_at(xs + eps, ts) - mu_at(xs - eps, ts)) / (2 * eps)
    err_x = np.max(np.abs(dx_num - dpm))

    v = 0.37
    dt_num = (mu_at(xs + v * eps, ts + eps)
              - mu_at(xs - v * eps, ts - eps)) / (2 * eps)
    err_t = np.max(np.abs(dt_num - dpm * (v - vbar)))

    print(f"  Prop 3, all pairs   max|d_x mu - Dp/hbar|    = {err_x:.3e}")
    print(f"  Prop 3, all pairs   max|dmu/dt - (Dp/h)(v-v)| = {err_t:.3e}")
    print("  -> the two-index family is generated by the one-index field Phi.")
    print("     A stored partner index carries no state; it can only select.")
    return dict(anti=anti, tri=tri, gauge=gauge, reref=reref)


