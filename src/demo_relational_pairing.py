# Part C -- the carrier-lock postulate                                  #
# --------------------------------------------------------------------- #
def part_C(rng):
    banner("Part C -- postulate (S), carrier lock: all-pairs == partnered")

    B = 2000
    x_cell, t = 3.1, 0.0
    s = +1
    mu_place = wrap(s * (K_MODE * x_cell + PHI_Q) + np.pi / 2.0)

    chi = rng.uniform(0.0, 2.0 * np.pi)                 # ONE carrier per site
    Phi_lo = np.full(B, chi)
    Phi_hi = np.full(B, chi + mu_place)

    part = np.mean(np.cos(wrap(Phi_hi - Phi_lo)))
    Zh = np.exp(1j * Phi_hi).sum()
    Zl = np.exp(1j * Phi_lo).sum()
    allp = np.real(Zh * np.conj(Zl)) / B ** 2

    print(f"  B = {B} sea particles per row at the site, t = {t}")
    print(f"  mu(place)                              = {mu_place:+.15f}")
    print(f"  partnered <cos mu>                     = {part:+.15f}")
    print(f"  all-pairs Re(Zhat_hi conj(Zhat_lo))    = {allp:+.15f}")
    print(f"  cos(mu_place)                          = "
          f"{np.cos(mu_place):+.15f}")
    print(f"  |all-pairs - partnered|                = "
          f"{abs(allp - part):.3e}")
    print(f"  |Zhat_hi| = {abs(Zh) / B:.15f}, |Zhat_lo| = {abs(Zl) / B:.15f}")
    print("  -> under (S) the indexed rule is the |Zhat| = 1 limit of the")
    print("     relational rule, and the site carrier chi cancels exactly.")
    return dict(mu_place=mu_place, part=part, allp=allp)


