# Part D -- factorisation                                               #
# --------------------------------------------------------------------- #
def part_D(rng):
    banner("Part D -- exact factorisation of the relational vertex sum")

    w0, kappa = 0.25, 0.10
    print(f"  w0 = {w0}, kappa = {kappa}   (clamp: kappa <= min(w0, 1-w0))")
    print()
    print(f"  {'N_hi':>7s} {'N_lo':>7s} {'direct O(N^2)':>18s} "
          f"{'factorised O(N)':>18s} {'rel.err':>10s} {'speedup':>9s}")
    rows = []
    for n in (8, 32, 128, 512, 2048, 8192):
        Phi_hi = rng.uniform(0.0, 2.0 * np.pi, size=n)
        Phi_lo = rng.uniform(0.0, 2.0 * np.pi, size=n)

        t0 = time.perf_counter()
        direct = np.sum(w0 + kappa * np.cos(Phi_hi[:, None] - Phi_lo[None, :]))
        t_d = time.perf_counter() - t0

        t0 = time.perf_counter()
        Zh = np.exp(1j * Phi_hi).sum()
        Zl = np.exp(1j * Phi_lo).sum()
        fact = w0 * n * n + kappa * np.real(Zh * np.conj(Zl))
        t_f = time.perf_counter() - t0

        rel = abs(direct - fact) / abs(direct)
        rows.append((n, rel, t_d / t_f))
        print(f"  {n:7d} {n:7d} {direct:18.10e} {fact:18.10e} "
              f"{rel:10.2e} {t_d / t_f:8.1f}x")

    print()
    print("  Identity (exact, not an approximation):")
    print("    sum_{a,b} [w0 + kappa cos(Phi_a - Phi_b)]")
    print("      = w0 N_hi N_lo + kappa Re( Z_hi conj(Z_lo) ).")
    print("  §4's O(N_exc * B) encounter loop becomes O(N_exc + N_sea), and")
    print("  the sea-subsampling workaround of §4 becomes unnecessary.")
    return rows


