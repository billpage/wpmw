"""
Relational (all-pairs) misalignment, and the carrier-lock condition it needs.

Companion to a proposed revision of
``docs/algorithm/phase_alignment_microdynamics_algorithm.md`` §2.2, which
currently stores on every sea particle a permanent index to a partner and
defines the misalignment as the transported-phase difference of that stored
pair.  The alternative under test (B. Page, July 2026) is to define

    mu_{ij}(x,t) = Phi_i(x,t) - Phi_j(x,t)   (mod 2 pi)

for *every* ordered pair of world-particle indices, storing no partnership
at all.

The result is that the alternative works, but not for free.  It is exactly
equivalent to the indexed form under one extra condition -- that the sea's
*carrier* phase be locked across pairs at a site, not merely matched within
each pair -- and it is inequivalent, in the mean and not just in variance,
when that condition fails.  The condition is not currently stated anywhere
in the model; it is the price of the reformulation, and it is testable.

Parts:

  A  Coboundary structure.  mu_{ij} is antisymmetric and satisfies the
     triangle (cocycle) identity exactly, so the two-index family is
     generated by the one-index field Phi.  Proposition 3 of
     ``docs/analysis/phase_alignment_microdynamics.md`` holds for arbitrary
     index pairs, not only for partners.

  B  The obstruction.  Lemma 1's darkness condition fixes only the
     *difference* of a pair's phases, leaving a free per-pair carrier.
     Averaging cos mu over all pairs is carrier-sensitive; averaging over
     partnered pairs is not.  With free carriers the all-pairs average is
     suppressed by 1/B and the reformulation fails.

  C  The carrier-lock postulate (S).  Impose a common transported phase per
     (cell, row) -- the literal reading of "phase-space *crystal* lattice"
     -- and the all-pairs average equals the indexed average identically.

  D  Factorisation.  Under (S) the double sum over admissible pairs
     collapses exactly onto a per-cell, per-row order parameter
         Z_n(x) = sum_j exp(i Phi_j(x,t)),
     turning the O(N_exc * B) vertex loop of §4 into O(N_exc + N_sea).

  E  Calibration.  The quadrature built from Z alone reproduces
     Gamma_q(x) = -(V_q/hbar) sin(K_q x + phi_q) with the corrected sign,
     the carrier cancelling identically.

  F  The deciding experiment.  Under per-particle noise the two forms agree
     in the mean and differ in variance by sqrt(N).  Under pair-correlated
     noise -- a sea of individually aligned but mutually randomised pairs --
     they differ in the mean, the indexed form reporting full response where
     the relational form reports none.

  H  Cells and rows.  The two labels in postulate (S) are not the same
     kind of thing: a momentum row is an exact lattice site, a spatial
     cell is a sweepable quadrature bin.  Part H verifies that same-row
     particles contribute identical transported phase regardless of
     their positions within the cell, and that the one place cell width
     does enter -- the pump, which samples V at each particle's own
     position -- produces a bounded rather than secular loss of carrier
     lock under free streaming.

  G  Sea consumption.  Corollaries 4.2/4.3 leave a struck pair with
     Delta p = 0 and hence permanently inert, so an indexed sea is a
     consumable resource with no replenishment in §6.  Part G sizes the
     deficit for the cosine-well demo.

Conventions follow the rest of the project: ring [0, L), half-grid
dp = pi hbar / L, mode quantum 2q dp = hbar K_q, stencil rows n +- q.
"""

