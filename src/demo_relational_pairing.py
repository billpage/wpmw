# Part F -- the deciding experiment                                     #
# --------------------------------------------------------------------- #
def part_F(rng, n_trials=400):
    banner("Part F -- the deciding experiment: two decoherence models")

    mu0 = 0.7
    Ns = np.array([16, 64, 256, 1024, 4096])

    print("  Model I -- independent per-particle phase noise (uniform):")
    print(f"  {'N':>6s} {'partnered rms':>16s} {'relational rms':>17s} "
          f"{'ratio':>8s}")
    rms_p, rms_r = [], []
    for N in Ns:
        vp, vr = [], []
        for _ in range(n_trials):
            da = rng.uniform(0.0, 2.0 * np.pi, size=N)
            db = rng.uniform(0.0, 2.0 * np.pi, size=N)
            vp.append(np.mean(np.cos(mu0 + da - db)))
            Zh = np.exp(1j * (mu0 + da)).sum()
            Zl = np.exp(1j * db).sum()
            vr.append(np.real(Zh * np.conj(Zl)) / N ** 2)
        rp = float(np.sqrt(np.mean(np.square(vp))))
        rr = float(np.sqrt(np.mean(np.square(vr))))
        rms_p.append(rp)
        rms_r.append(rr)
        print(f"  {N:6d} {rp:16.4e} {rr:17.4e} {rp / rr:7.1f}x")

    ep = float(np.polyfit(np.log(Ns), np.log(rms_p), 1)[0])
    er = float(np.polyfit(np.log(Ns), np.log(rms_r), 1)[0])
    print(f"  fitted exponents:  partnered N^({ep:+.3f}),  "
          f"relational N^({er:+.3f})")
    print("  -> identical mean (zero); relational form is sqrt(N) quieter.")
    print()
    print("  Model II -- pair-correlated noise: each pair keeps its own mu,")
    print("              pairs mutually randomised (Lemma 5 violated):")
    N = 4096
    delta = rng.uniform(0.0, 2.0 * np.pi, size=N)
    Phi_lo, Phi_hi = delta, delta + mu0
    part = float(np.mean(np.cos(wrap(Phi_hi - Phi_lo))))
    Zh = np.exp(1j * Phi_hi).sum()
    Zl = np.exp(1j * Phi_lo).sum()
    rel = float(np.real(Zh * np.conj(Zl)) / N ** 2)
    print(f"  N = {N},  mu = {mu0}")
    print(f"  partnered  <cos mu>                  = {part:+.6f}  "
          f"(= cos mu, full response)")
    print(f"  relational Re(Zhat_hi conj(Zhat_lo)) = {rel:+.6f}  "
          f"(suppressed ~ 1/N)")
    print("  -> the two forms disagree in the MEAN, not just in variance.")
    print("     The partnered estimator reports a coherent grating where")
    print("     there is none; it cannot detect failure of Lemma 5, which")
    print("     is the assumption it silently makes.")
    return Ns, np.array(rms_p), np.array(rms_r), ep, er, part, rel


