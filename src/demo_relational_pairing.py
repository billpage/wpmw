def part_B(rng):
    banner("Part B -- the obstruction: a free per-pair carrier kills all-pairs")

    mu0 = 0.7
    print(f"  true misalignment mu = {mu0}, cos mu = {np.cos(mu0):+.6f}")
    print()
    print(f"  {'B':>6s} {'partnered <cos mu>':>22s} "
          f"{'all-pairs <cos mu>':>22s}")
    rows = []
    for B in (32, 128, 512, 2048, 8192):
        chi = rng.uniform(0.0, 2.0 * np.pi, size=B)     # free carrier per pair
        Phi_lo, Phi_hi = chi, chi + mu0
        part = np.mean(np.cos(wrap(Phi_hi - Phi_lo)))
        allp = np.real(np.exp(1j * Phi_hi).sum()
                       * np.conj(np.exp(1j * Phi_lo).sum())) / B ** 2
        rows.append((B, part, allp))
        print(f"  {B:6d} {part:22.9f} {allp:22.9f}")
    print()
    print("  Lemma 1 fixes only theta_a - theta_b within a pair; the common")
    print("  value is unconstrained.  Under that reading mu_{ij} across")
    print("  different pairs is not gauge invariant, and Bill's definition")
    print("  averages to zero as 1/B.  The reformulation needs one more")
    print("  ingredient, supplied in Part C.")
    return rows


