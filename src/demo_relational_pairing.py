def part_G():
    banner("Part G -- an indexed sea is consumable; a relational sea is not")

    omega = np.sqrt(V_P * (2.0 * np.pi / L) ** 2 / MASS)
    T_period = 2.0 * np.pi / omega
    T_final = 4.0 * T_period
    N_exc, M, B = 5_000_000, 128, 2_000
    gamma_max = V_P / HBAR
    fires = gamma_max * T_final * N_exc / M

    print(f"  cosine-well demo: V_p = {V_P}, L = {L}, "
          f"N_exc = {N_exc:,}, M = {M}")
    print(f"  harmonic period T = {T_period:.3f}, T_final = {T_final:.3f}")
    print(f"  max|Gamma_q| = V_p/hbar = {gamma_max}")
    print(f"  NET firings required per cell over the run   ~ {fires:.3e}")
    print(f"  distinct pairs available per cell (B = {B})   = {B:.3e}")
    print(f"  shortfall factor                             ~ {fires / B:.2e}")
    print("  (gross traffic at rate w0 makes this a lower bound)")
    print()
    print("  Corollary 4.2 leaves a struck pair at Delta p = 0; Corollary 4.3")
    print("  then gives it transfer size |Delta p| = 0, so it can never")
    print("  mediate again.  §6's pump writes phases only (Lemma 3), so")
    print("  nothing replenishes the split population, and §9's reference")
    print("  loop populates pairs once at initialisation.  Under the")
    print("  relational definition, admissibility is re-derived from row")
    print("  occupancy each step, so a struck particle rejoins the")
    print("  admissible set immediately and the resource never depletes.")
    return fires, B


