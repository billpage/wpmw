    e = float(np.sqrt(np.mean(np.square(errs))))
    H_rows.append((N0, e))
    print(f"  N0 = {N0:7d}:  rms L2 error (4 seeds) = {e:.4f}   e*sqrt(N0) = {e*np.sqrt(N0):6.2f}"
          f"   population / N0 = {np.mean(pops):.1f}")

