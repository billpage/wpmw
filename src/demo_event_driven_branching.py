#!/usr/bin/env python3
r"""
Independent re-implementation of Cyganski's event-driven "virtual-photon pair
branching" (call of 2026-09-29), for the supplement
docs/supplement/poisson_kicks_and_pair_branching.md, Parts F-M (prefix X).

Model.  V(x) = omega^2 x^2 / 2 + V1 sin(k x),  hbar = m = 1,
omega = 0.4, V1 = 0.5, k = 1, initial Gaussian at rest at x0 = 6, sigma_x = 0.7.
The quadratic part is an exact classical flow; the sine acts through events on
a Poisson clock generated by thinning (src/wpmwlib/event_branching.py).

Parts
  F  Two independent references: split-operator Schroedinger (|psi|^2) and a
     spectral QLE solver on (x, p).  They must agree.
  G  Infinite-N limits.  Signed pair branching IS the QLE (Lemma T1);
     one-particle positive kicks (step hbar k, Cyganski's slide, and hbar k/2)
     are not: marginals, phase space, and the exact heating law
     d<H>/dt = <M2>/2 (Proposition X4).
  H  Pair branching WITHOUT annihilation is unbiased:  error * sqrt(N0) const.
  I  With cell annihilation: N0-scaling at three momentum cells h_p.  The error
     plateaus -- a bias set by h_p, not by N0 (Proposition X5).
  J  What controls the bias: h_p versus h_x, and the synchronisation interval.
  K  Negative control by Monte Carlo: one-particle kicks agree with their own
     master equation and not with the QLE; measured heating vs Proposition X4.
  L  Clock: thinning (exact) versus a rate frozen at the start of each flight.
"""

import os
import sys
import time

import numpy as np

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from wpmwlib.wpmw_utils import output_path, docs_path  # noqa: E402
from wpmwlib.event_branching import EventBranching  # noqa: E402

OM, V1, K = 0.4, 0.5, 1.0
X0, SX = 6.0, 0.7
SP = 1.0 / (2 * SX)
T_OBS = 9.0
FIG1, FIG2 = "event_branching_phase_space.png", "event_branching_bias.png"
QUICK = os.environ.get("WPMW_QUICK", "") == "1"   # smaller N0 for a smoke test


def banner(s):
    print("\n" + "=" * 72)
    print(s)
    print("=" * 72, flush=True)


def V(x):
    return 0.5 * OM ** 2 * x ** 2 + V1 * np.sin(K * x)


# ----------------------------------------------------------------------
# spectral phase-space solver (QLE, or quadratic force + positive kicks)
# ----------------------------------------------------------------------
MX, NP, LX, LP = 256, 512, 25.6, 32.0
xg = (np.arange(MX) - MX // 2) * (LX / MX)
pg = (np.arange(NP) - NP // 2) * (LP / NP)
DXG, DPG = LX / MX, LP / NP
X, P = np.meshgrid(xg, pg, indexing="xy")
kx = 2 * np.pi * np.fft.fftfreq(MX, d=DXG)
kp = 2 * np.pi * np.fft.fftfreq(NP, d=DPG)


def W_init(Xa, Pa):
    return np.exp(-(Xa - X0) ** 2 / (2 * SX ** 2) - Pa ** 2 / (2 * SP ** 2)) / (2 * np.pi * SX * SP)


def spectral(times, rule="qle", step=K, dt=0.01):
    """Strang split.  rule='qle': exact potential symbol i[V(x+k/2)-V(x-k/2)];
    rule='one': omega^2 x force + rate |F|/step jumps of step*sgn F."""
    W = W_init(X, P).astype(complex)
    KP, XX = kp[:, None], xg[None, :]
    if rule == "qle":
        G = 1j * (V(XX + KP / 2) - V(XX - KP / 2))
    else:
        F = -V1 * K * np.cos(K * XX)
        G = 1j * OM ** 2 * XX * KP + (np.abs(F) / step) * (np.exp(-1j * KP * step * np.sign(F)) - 1)
    kick = np.exp(G * dt)
    half = np.exp(-1j * kx[None, :] * P * dt / 2)
    out = {}
    nmax = int(round(max(times) / dt))
    want = {int(round(t / dt)): t for t in times}
    for i in range(1, nmax + 1):
        W = np.fft.ifft(np.fft.fft(W, axis=1) * half, axis=1)
        W = np.fft.ifft(np.fft.fft(W, axis=0) * kick, axis=0)
        W = np.fft.ifft(np.fft.fft(W, axis=1) * half, axis=1)
        if i in want:
            out[want[i]] = W.real.copy()
    return out


def energy(W):
    return float(np.sum((P ** 2 / 2 + V(X)) * W) * DXG * DPG)


def xmean(W):
    return float(np.sum(X * W) * DXG * DPG)


# ----------------------------------------------------------------------
banner("PART F  --  references: Schroedinger |psi|^2 vs spectral QLE")
NS, LS = 4096, 60.0
xs = (np.arange(NS) - NS // 2) * (LS / NS)
dxs = LS / NS
ks = 2 * np.pi * np.fft.fftfreq(NS, d=dxs)
psi = ((2 * np.pi * SX ** 2) ** -0.25 * np.exp(-(xs - X0) ** 2 / (4 * SX ** 2))).astype(complex)
dts = 0.0025
hv, kin = np.exp(-0.5j * V(xs) * dts), np.exp(-0.5j * ks ** 2 * dts)
rho_s = {}
for i in range(1, int(round(T_OBS / dts)) + 1):
    psi = hv * np.fft.ifft(kin * np.fft.fft(hv * psi))
    for t in (4.5, T_OBS):
        if i == int(round(t / dts)):
            rho_s[t] = np.abs(psi) ** 2

t_grid = np.round(np.arange(0.5, 18.0 + 1e-9, 0.5), 3)
t0 = time.time()
Q = spectral(sorted(set(t_grid) | {4.5, T_OBS}))
print(f"  spectral QLE {MX}x{NP}, dt = 0.01: {time.time() - t0:.1f} s")
for t in (4.5, T_OBS):
    rq = Q[t].sum(0) * DPG
    d = np.abs(rq - np.interp(xg, xs, rho_s[t])).max()
    print(f"  t = {t:4.1f}:  max |rho_QLE - |psi|^2| = {d:.2e}   (peak {rho_s[t].max():.4f})")
# return turning point: first maximum of <x> after the left excursion
xm = np.array([xmean(Q[t]) for t in t_grid])
sel = (t_grid > 10)
T_RET = float(t_grid[sel][np.argmax(xm[sel])])
Q.update(spectral([T_RET]))
print(f"  return turning point (max <x> on a 0.5 grid, t > 10): T_ret = {T_RET}"
      f"   <x> = {xmean(Q[T_RET]):.3f}")
E0 = energy(W_init(X, P))
dE_qle = max(abs(energy(Q[t]) - E0) for t in t_grid)
print(f"  QLE energy <H> = {E0:.6f},  max drift over t <= 18: {dE_qle:.2e}")

# ----------------------------------------------------------------------
banner("PART G  --  infinite-N limits: pair branching (= QLE) vs one-particle kicks")
print("  Pair branching:  Gamma(x)[W(p+a)-W(p-a)], a = hbar k/2, IS the sine's exact")
print("  Wigner term (Lemma T1).  Its infinite-N limit is the QLE identically.")
for t in (T_OBS, T_RET):
    print(f"  QLE, t = {t:5.2f}:  negative mass = {-Q[t][Q[t] < 0].sum() * DXG * DPG:.4f}   "
          f"purity 2*pi*hbar*int W^2 = {2 * np.pi * np.sum(Q[t] ** 2) * DXG * DPG:.4f}")
ONE = {}
for label, step in (("step hbar k  ", K), ("step hbar k/2", K / 2)):
    t_fine = np.round(np.arange(0.1, 18.0 + 1e-9, 0.1), 3)
    R1 = spectral(sorted(set([4.5, T_OBS, T_RET]) | set(t_fine)), rule="one", step=step)
    ONE[step] = R1
    for t in (T_OBS, T_RET):
        l1W = np.abs(R1[t] - Q[t]).sum() * DXG * DPG
        l1r = np.abs(R1[t].sum(0) - Q[t].sum(0)).sum() * DPG * DXG
        neg = -R1[t][R1[t] < 0].sum() * DXG * DPG
        pur = 2 * np.pi * np.sum(R1[t] ** 2) * DXG * DPG
        print(f"  one-particle, {label}, t = {t:5.2f}:  ||W - W_QLE||_1 = {l1W:.3f}   "
              f"||rho - rho_QLE||_1 = {l1r:.3f}   negative mass = {neg:.2e}   "
              f"purity 2*pi*hbar*int W^2 = {pur:.4f}")
    # Proposition X4: d<H>/dt = <M2>/2,  M2 = step |F| = step V1 k |cos kx|
    tt_ = np.concatenate([[0.0], t_fine])
    Et = np.array([E0] + [energy(R1[t]) for t in t_fine])
    W0_ = W_init(X, P)
    rate = np.array([0.5 * step * V1 * K * np.sum(np.abs(np.cos(K * X)) * Wt) * DXG * DPG
                     for Wt in [W0_] + [R1[t] for t in t_fine]])
    pred = E0 + np.concatenate([[0], np.cumsum(0.5 * (rate[1:] + rate[:-1]) * np.diff(tt_))])
    print(f"      heating: <H>(18) - <H>(0) = {Et[-1] - E0:.4f};  "
          f"integral of <M2>/2 = {pred[-1] - E0:.4f};  "
          f"max |<H> - prediction| = {np.abs(Et - pred).max():.2e}")
QLE_W = Q

# ----------------------------------------------------------------------
edges = np.arange(-12.0, 12.0 + 1e-9, 0.1)
HX = 0.1
xc = 0.5 * (edges[1:] + edges[:-1])


def ref_bins(rho):
    cum = np.concatenate([[0.0], np.cumsum(rho) * dxs])
    xe = np.concatenate([xs - dxs / 2, [xs[-1] + dxs / 2]])
    return np.diff(np.interp(edges, xe, cum)) / HX


REF = {t: ref_bins(rho_s[t]) for t in rho_s}


def mc(N0, T, seed, rule="pair", cell=(0.1, 0.25), t_sync=0.1, annihilate=True,
       clock="thin", step=K, callback=None, ann_mode="keep"):
    rng = np.random.default_rng(seed)
    x = rng.normal(X0, SX, N0)
    p = rng.normal(0.0, SP, N0)
    s = np.ones(N0, np.int8)
    eb = EventBranching(OM, V1, K, rule=rule, step=step, clock=clock, cell=cell,
                        annihilation=ann_mode, rng=rng)
    if annihilate or rule == "one":
        out, log = eb.run(x, p, s, [T], t_sync, callback=callback)
        x, p, s = out[T]
    else:
        x, p, s = eb.advance(x, p, s, 0.0, T)
        log = np.array([[T, x.size, (s > 0).sum(), (s < 0).sum()]])
    h, _ = np.histogram(x, bins=edges, weights=s.astype(float))
    return h / N0 / HX, (x, p, s), log, eb


def l2(r, T):
    return float(np.sqrt(np.sum((r - REF[T]) ** 2) * HX))


PEAK = int(np.argmax(REF[T_OBS]))
