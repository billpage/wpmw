    (b2, cc), *_ = np.linalg.lstsq(A, Es ** 2, rcond=None)
    print(f"      fit e^2 = b^2 + c/N0:  b = {np.sqrt(max(b2, 0)):.4f}   sqrt(c) = {np.sqrt(max(cc, 0)):.1f}"
          f"   ||pooled mean - ref||_2 = {l2(pooled, T_OBS):.4f} (pooled N = {wsum})")
